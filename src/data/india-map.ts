function draw(points: number[][], close = true) {
  return points.map(([lng,lat], i) => {
    const point = projectIndia(lng,lat);
    return `${i ? "L" : "M"}${point.x.toFixed(1)} ${point.y.toFixed(1)}`;
  }).join(" ") + (close ? " Z" : "");
}
