/** Called by the guarded Weekend Trips acceptance runner, with its synthetic fixtures. */
import assert from 'node:assert/strict';
import path from 'node:path';
import { newCmsSection } from '../../src/lib/cms.ts';

export async function cmsCatalogueAcceptance({ adminPage, browser, base, api, admin, customer, pool, packageId, category, regionId, cityId, trip, createdPages, artifacts, errors }: any) {
  let checks = 0;
  async function request(url: string, actor = admin, method = 'GET', body?: unknown, status = 200) {
    const response = await api(url, actor, method, body); checks++; assert.equal(response.status, status, `${method} ${url}: ${await response.clone().text()}`); return response.json();
  }
  await request('/api/admin/cms/options', null, 'GET', undefined, 401);
  await request('/api/admin/cms/options', customer, 'GET', undefined, 403);
  await request('/api/admin/cms/options', admin, 'POST', { kind: 'destination', href: '/admin/users' }, 400);
  await request('/api/admin/cms/options', admin, 'POST', { kind: 'filtered', source: 'vehicles', filters: { sql: 'all' } }, 400);
  // This existing test package is now also offered privately for catalogue checks.
  await pool.query("UPDATE packages SET booking_mode='both' WHERE package_id=$1 AND created_by=$2", [packageId, admin.id]);
  const choices = await request('/api/admin/cms/options');
  assert(choices.destinations.some((d: any) => d.href === '/weekend-trips/' + trip.slug));
  assert(!JSON.stringify(choices).includes('PRIVATE-REFERENCE'));
  const slug = 'cms-' + trip.slug;
  let current = (await request('/api/admin/cms/pages', admin, 'POST', { slug, title: 'CMS catalogue acceptance', template: 'blank' }, 201)).item;
  createdPages.push(current.id);
  const route = '/api/admin/cms/pages/' + current.id;
  current = (await request(route, admin, 'PATCH', { action: 'publish', version: current.version })).item;
  const oldRevision = (await request(route)).revisions[0].id;
  const editor = await adminPage.context().newPage(); editor.on('pageerror', (e: Error) => errors.push(e.message));
  await editor.goto(base + '/admin/pages/' + current.id, { waitUntil: 'domcontentloaded' });
  await editor.getByRole('button', { name: '+ Add section', exact: true }).click();
  await editor.getByRole('dialog').getByRole('button', { name: /^Live catalogue Choose/ }).click();
  await editor.getByLabel('Content source', { exact: true }).selectOption('vehicles');
  await editor.getByLabel('Vehicle category', { exact: true }).selectOption(category);
  assert.equal(await editor.getByLabel('Pickup city', { exact: true }).count(), 0);
  await editor.getByLabel('Content source', { exact: true }).selectOption('packages');
  assert.equal(await editor.getByLabel('Vehicle category', { exact: true }).count(), 0);
  await editor.getByLabel('Destination region', { exact: true }).selectOption(String(regionId));
  await editor.getByLabel('Content source', { exact: true }).selectOption('weekend-trips');
  await editor.getByLabel('Heading', { exact: true }).fill('Friday CMS selection');
  await editor.getByLabel('Pickup city', { exact: true }).selectOption(String(cityId));
  await editor.getByLabel('Minimum price (₹)', { exact: true }).fill('4999');
  await editor.getByLabel('Maximum price (₹, 0 = any)', { exact: true }).fill('4999');
  await editor.getByLabel('Only featured trips', { exact: true }).check();
  for (const label of ['Show search', 'Show destination filter', 'Show pickup filter', 'Show departure date filters', 'Show budget filter', 'Show group-size filter', 'Show sort control']) await editor.getByLabel(label, { exact: true }).check();
  await editor.getByRole('button', { name: 'Choose destination', exact: true }).click();
  let link = editor.getByRole('dialog', { name: 'Choose link destination', exact: true });
  await link.getByLabel('Link type', { exact: true }).selectOption('anchor');
  await link.getByLabel('Destination', { exact: true }).selectOption({ index: 1 });
  await link.getByRole('button', { name: 'Use this link', exact: true }).click(); await link.waitFor({ state: 'hidden' });
  assert((await editor.getByLabel('Button link', { exact: true }).inputValue()).startsWith('#section-'));
  await editor.getByRole('button', { name: 'Choose destination', exact: true }).click();
  link = editor.getByRole('dialog', { name: 'Choose link destination', exact: true });
  await link.getByLabel('Link type', { exact: true }).selectOption('external');
  await link.getByLabel('Website address', { exact: true }).fill('javascript:alert(1)');
  await link.getByRole('button', { name: 'Use this link', exact: true }).click(); await link.getByRole('alert').waitFor();
  await link.getByLabel('Link type', { exact: true }).selectOption('filtered');
  await link.getByLabel('Pickup city', { exact: true }).selectOption(String(cityId));
  await link.getByLabel('Maximum price (₹)', { exact: true }).fill('4999');
  await link.getByRole('button', { name: 'Use this link', exact: true }).click(); await link.waitFor({ state: 'hidden' });
  const href = await editor.getByLabel('Button link', { exact: true }).inputValue();
  assert.equal(new URL(href, base).searchParams.get('cityId'), String(cityId));
  await editor.getByRole('button', { name: 'Preview', exact: true }).click();
  const preview = editor.getByRole('dialog', { name: 'Preview your page', exact: true }); await preview.waitFor();
  const frame = editor.frameLocator('iframe');
  await frame.getByRole('heading', { name: trip.title, exact: true }).waitFor();
  await preview.getByRole('button', { name: 'Close dialog', exact: true }).click();
  assert(!(await (await api('/' + slug, null)).text()).includes('Friday CMS selection'), 'Saved draft stays private');
  await editor.getByRole('button', { name: 'Publish', exact: true }).click();
  const publish = editor.getByRole('dialog', { name: 'Publish CMS catalogue acceptance?', exact: true });
  await publish.getByRole('button', { name: 'Publish page', exact: true }).click(); await publish.waitFor({ state: 'hidden' });
  current = (await request(route)).item;
  const section = current.draft.sections.find((s: any) => s.type === 'catalogue'); assert(section);
  assert.equal(section.content.category, ''); assert.equal(section.content.source, 'weekend-trips');
  if (artifacts) await editor.screenshot({ path: path.join(artifacts, 'cms-catalogue-editor.png') });
  // Both other sources render the existing public catalogue through the same model.
  const vehicles = newCmsSection('catalogue', 'fixture-vehicles'); Object.assign(vehicles.content, { source: 'vehicles', title: 'CMS vehicles', category, buttonHref: '/vehicles', buttonLabel: 'All vehicles' });
  const packages = newCmsSection('catalogue', 'fixture-packages'); Object.assign(packages.content, { source: 'packages', title: 'CMS packages', region: regionId, minPrice: 4999, maxPrice: 4999, buttonHref: '/packages', buttonLabel: 'All packages' });
  const empty = newCmsSection('catalogue', 'fixture-empty'); Object.assign(empty.content, { minPrice: 1, maxPrice: 1, empty: 'hide' });
  current.draft.sections.push(vehicles, packages, empty);
  current = (await request(route, admin, 'PATCH', { action: 'save', title: current.title, draft: current.draft, version: current.version })).item;
  current = (await request(route, admin, 'PATCH', { action: 'publish', version: current.version })).item;
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const publicPage = await context.newPage(); publicPage.on('pageerror', (e: Error) => errors.push(e.message));
  await publicPage.goto(base + '/' + slug, { waitUntil: 'domcontentloaded' });
  const block = publicPage.locator(`[data-cms-catalogue="${section.id}"]`);
  await block.getByRole('heading', { name: trip.title, exact: true }).waitFor();
  assert.equal(await publicPage.locator('[data-cms-catalogue="fixture-vehicles"] article').count(), 1);
  assert((await publicPage.locator('[data-cms-catalogue="fixture-packages"]').innerText()).includes(trip.slug));
  assert.equal(await publicPage.locator('[data-cms-catalogue="fixture-empty"]').count(), 0);
  const body = await publicPage.locator('body').innerText(); for (const hidden of ['PRIVATE-REFERENCE', 'PRIVATE-HOTEL-NOTE', 'Internal operations']) assert(!body.includes(hidden));
  await block.getByLabel('Maximum price (₹)', { exact: true }).fill('1'); assert.equal(await block.locator('article').count(), 0);
  await block.getByRole('button', { name: 'Reset filters' }).click();
  await block.getByLabel('Group size', { exact: true }).fill('11'); assert.equal(await block.locator('article').count(), 0);
  await block.getByRole('button', { name: 'Reset filters' }).click();
  await block.getByLabel('Departure from', { exact: true }).fill('2199-01-01'); assert.equal(await block.locator('article').count(), 0);
  await block.getByRole('button', { name: 'Reset filters' }).click();
  await block.getByLabel('Search catalogue', { exact: true }).fill(trip.title); assert.equal(await block.locator('article').count(), 1);
  assert.equal(await block.getByRole('link', { name: trip.title, exact: true }).getAttribute('href'), '/weekend-trips/' + trip.slug);
  const filtered = await request('/api/admin/cms/options', admin, 'POST', { kind: 'filtered', source: 'packages', filters: { regionId } });
  const listing = await context.newPage(); await listing.goto(base + filtered.href); assert((await listing.locator('body').innerText()).includes(trip.slug)); await listing.close();
  if (artifacts) await publicPage.screenshot({ path: path.join(artifacts, 'cms-catalogue-public.png'), fullPage: true });
  await publicPage.setViewportSize({ width: 390, height: 844 });
  assert(await publicPage.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  if (artifacts) await publicPage.screenshot({ path: path.join(artifacts, 'cms-catalogue-mobile.png') });
  // Restoring a pre-upgrade revision changes only the draft and keeps public catalogue intact.
  const restored = (await request(route, admin, 'PATCH', { action: 'restore', version: current.version, revisionId: oldRevision })).item;
  assert.equal(restored.draft.sections.length, 1); assert.equal(restored.draft.sections[0].type, 'text');
  assert((await (await api('/' + slug, null)).text()).includes('Friday CMS selection'));
  await editor.close();
  console.log(`PASS CMS catalogue: ${checks} HTTP checks, source-specific editor, real destination picker, preview/publish, all three catalogues, visitor filters, mobile and old-revision restore.`);
  return { page: publicPage, sectionId: section.id };
}
